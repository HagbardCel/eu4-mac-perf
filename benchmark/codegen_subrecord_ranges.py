#!/usr/bin/env python3
"""Generate subrecord_equivalence_ranges.inc from layout JSON (single source of truth)."""

from __future__ import annotations

from pathlib import Path

from mesh_record_layout import export_tables

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "subrecord_equivalence_ranges.inc"

POLICY_C = {"equal": "EU4_CMP_EQUAL", "ignore": "EU4_CMP_IGNORE", "barrier": "EU4_CMP_BARRIER"}


def _emit_table(name: str, c_symbol: str, count_symbol: str, ranges: list[tuple[int, int, str]]) -> str:
    lines = [f"const eu4_layout_range_t {c_symbol}[] = {{"]
    for offset, size, policy in ranges:
        lines.append(f"    {{{offset:#x}, {size}, {POLICY_C[policy]}}},")
    lines.append("};")
    lines.append(f"const size_t {count_symbol} = sizeof({c_symbol}) / sizeof({c_symbol}[0]);")
    return "\n".join(lines)


def generate() -> str:
    tables = export_tables()
    sflush = [(r["offset"], r["size"], r["comparison_policy"]) for r in tables["sflushdata_0x50"]["ranges"]]
    mesh = [(r["offset"], r["size"], r["comparison_policy"]) for r in tables["mesh_draw_subrecord_0xe8"]["ranges"]]
    body = "\n\n".join(
        [
            "/* Generated by codegen_subrecord_ranges.py — do not edit. */",
            _emit_table("sflushdata", "eu4_sflushdata_ranges", "eu4_sflushdata_range_count", sflush),
            _emit_table("mesh_draw", "eu4_mesh_draw_ranges", "eu4_mesh_draw_range_count", mesh),
        ]
    )
    return body + "\n"


def main() -> None:
    OUT.write_text(generate(), encoding="utf-8")


if __name__ == "__main__":
    main()
