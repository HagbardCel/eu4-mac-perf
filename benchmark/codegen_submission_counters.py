#!/usr/bin/env python3
"""Generate submission counter schema artifacts from submission_counter_schema.json."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SCHEMA_PATH = ROOT / "submission_counter_schema.json"
OUT_H = ROOT / "submission_counter_schema.h"
OUT_PY = ROOT / "submission_counter_schema.py"


def _supported_mask(hypotheses: list[dict]) -> int:
    mask = 0
    for row in hypotheses:
        if row.get("supported_default"):
            mask |= 1 << int(row["bit"])
    return mask


def _safety_mask(hypotheses: list[dict]) -> int:
    mask = 0
    for row in hypotheses:
        if row.get("safety_qualified_default"):
            mask |= 1 << int(row["bit"])
    return mask


def generate_h(schema: dict) -> str:
    counters = schema["counters"]
    hypotheses = schema["hypotheses"]
    lines = [
        "/* Generated by codegen_submission_counters.py — do not edit. */",
        "#ifndef EU4_SUBMISSION_COUNTER_SCHEMA_H",
        "#define EU4_SUBMISSION_COUNTER_SCHEMA_H",
        "#include <stdint.h>",
        "",
        f"#define EU4_SUBMISSION_COUNTER_SCHEMA_VERSION {schema['schema_version']}u",
        f"#define EU4_SUBMISSION_COUNTER_COUNT {len(counters)}u",
        f"#define EU4_SUBMISSION_SUPPORTED_HYPOTHESIS_MASK_DEFAULT 0x{_supported_mask(hypotheses):x}u",
        f"#define EU4_SUBMISSION_SAFETY_HYPOTHESIS_MASK_DEFAULT 0x{_safety_mask(hypotheses):x}u",
        "",
        "typedef enum {",
    ]
    for c in counters:
        enum = "EU4_COUNTER_" + c["name"].upper()
        lines.append(f"    {enum} = {c['slot']},")
    lines.append("} eu4_submission_counter_slot_t;")
    lines.append("")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def generate_py(schema: dict) -> str:
    counters = schema["counters"]
    hypotheses = schema["hypotheses"]
    lines = [
        '"""Generated by codegen_submission_counters.py — do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        f"COUNTER_SCHEMA_VERSION = {schema['schema_version']}",
        f"COUNTER_COUNT = {len(counters)}",
        f"SUPPORTED_HYPOTHESIS_MASK_DEFAULT = 0x{_supported_mask(hypotheses):x}",
        f"SAFETY_HYPOTHESIS_MASK_DEFAULT = 0x{_safety_mask(hypotheses):x}",
        "",
        "COUNTER_SLOTS = {",
    ]
    for c in counters:
        lines.append(f'    "{c["name"]}": {c["slot"]},')
    lines.append("}")
    lines.append("")
    lines.append("HYPOTHESES = [")
    for h in hypotheses:
        lines.append(f"    {repr(h)},")
    lines.append("]")
    lines.append("")
    health = tuple(c["name"] for c in counters if c.get("bank") == "health")
    candidate = tuple(c["name"] for c in counters if c.get("bank") == "candidate")
    lines.append(f"HEALTH_COUNTER_NAMES = {health!r}")
    lines.append(f"CANDIDATE_COUNTER_NAMES = {candidate!r}")
    return "\n".join(lines) + "\n"


def main() -> None:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    OUT_H.write_text(generate_h(schema), encoding="utf-8")
    OUT_PY.write_text(generate_py(schema), encoding="utf-8")


if __name__ == "__main__":
    main()
