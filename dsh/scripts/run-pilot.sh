#!/bin/sh
# Run one model-driven headless DSH turn with the native EU4 tools mounted.
#
#   OPENCODE_GO_API_KEY=... ./dsh/scripts/run-pilot.sh \
#       --task-file <path> [--workspace <dir>] [--out <dir>] \
#       [--session-id <id>] [--permission-mode workspace-write] \
#       [--require-tool <name>]...
#
# This is the evidence-producing counterpart to run-campaign.sh: it boots the
# shipped headless profile plus one overlay (this checkout's tools plugin and
# skill root, the opencode-go provider), runs exactly the turn it is given,
# and preserves the persistent session export and its efficiency analysis.
# It does not schedule, drive or continue goal rounds; a caller that resumes a
# session does so explicitly with --session-id.
set -eu

HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
INFRA=$(CDPATH= cd -- "$HERE/../.." && pwd)
TASK_FILE=
WORKSPACE=$INFRA
OUT=
SESSION=
MODE=workspace-write
REQUIRE_TOOLS=
CAMPAIGN_STATE=

usage() {
  sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --task-file) TASK_FILE=${2:?--task-file needs a path}; shift 2 ;;
    --workspace) WORKSPACE=${2:?--workspace needs a path}; shift 2 ;;
    --out) OUT=${2:?--out needs a path}; shift 2 ;;
    --session-id) SESSION=${2:?--session-id needs an id}; shift 2 ;;
    --permission-mode) MODE=${2:?--permission-mode needs a value}; shift 2 ;;
    --require-tool) REQUIRE_TOOLS="$REQUIRE_TOOLS ${2:?--require-tool needs a name}"; shift 2 ;;
    --campaign-state) CAMPAIGN_STATE=${2:?--campaign-state needs a path}; shift 2 ;;
    -h|--help) usage 0 ;;
    *) echo "run-pilot: unknown option: $1" >&2; usage 2 ;;
  esac
done

[ -n "$TASK_FILE" ] || { echo "run-pilot: --task-file is required" >&2; exit 2; }
[ -f "$TASK_FILE" ] || { echo "run-pilot: task file not found: $TASK_FILE" >&2; exit 2; }
[ -d "$WORKSPACE" ] || { echo "run-pilot: workspace not found: $WORKSPACE" >&2; exit 2; }

case "$MODE" in
  read-only|workspace-write|danger-full-access) ;;
  *) echo "run-pilot: unsupported permission mode: $MODE" >&2; exit 2 ;;
esac

if [ -z "${OPENCODE_GO_API_KEY:-}" ]; then
  cat >&2 <<'EOF'
run-pilot: OPENCODE_GO_API_KEY is not set.
  The headless profile does not mount the credentials service on 0.2.2-rc.1,
  so export the key for this turn (do not write it into the repository):
    export OPENCODE_GO_API_KEY=...
    ./dsh/scripts/run-pilot.sh --task-file ...
EOF
  exit 2
fi

: "${EU4_DSH_HOME:=$HOME/.local/share/eu4-dsh}"
DSH_HOME=$EU4_DSH_HOME
export DSH_HOME
export EU4_DSH_SKILL_ROOT=${EU4_DSH_SKILL_ROOT:-$INFRA/.opencode/skills}

# Resolve the same absolute, NumPy-capable interpreter preflight verifies. An
# explicit EU4_DSH_PYTHON is authoritative and must already be usable.
PYTHON_REQUEST=${EU4_DSH_PYTHON:-}
if [ -z "$PYTHON_REQUEST" ]; then
  if [ -x "$INFRA/.venv/bin/python3" ]; then
    PYTHON_REQUEST=$INFRA/.venv/bin/python3
  elif command -v python3.14 >/dev/null 2>&1; then
    PYTHON_REQUEST=$(command -v python3.14)
  else
    PYTHON_REQUEST=$(command -v python3 || true)
  fi
fi
[ -n "$PYTHON_REQUEST" ] || {
  echo "run-pilot: no Python 3 interpreter is available on PATH" >&2
  exit 2
}
EU4_DSH_PYTHON=$(
  cd "$INFRA" && "$PYTHON_REQUEST" -m automation.python_runtime \
    resolve --requested "$PYTHON_REQUEST" --print-path
) || {
  echo "run-pilot: no Python 3 interpreter with NumPy; set EU4_DSH_PYTHON" >&2
  exit 2
}
export EU4_DSH_PYTHON

# Optional campaign safety state.  A pilot is autonomous reconstruction by
# default: it cannot launch EU4, and there is no replay/validation quota.
if [ -n "${CAMPAIGN_STATE:-}" ]; then
  EU4_CAMPAIGN_STATE=$(CDPATH= cd -- "$(dirname -- "$CAMPAIGN_STATE")" 2>/dev/null && pwd)/$(basename -- "$CAMPAIGN_STATE") || EU4_CAMPAIGN_STATE=$CAMPAIGN_STATE
  export EU4_CAMPAIGN_STATE
  ( cd "$INFRA" && "$EU4_DSH_PYTHON" -m automation.campaign_guard ensure \
      --state "$EU4_CAMPAIGN_STATE" --mode autonomous_reconstruction ) >&2 || {
    echo "$(basename "$0"): could not prepare the campaign state" >&2
    exit 1
  }
  echo "$(basename "$0"): campaign state=$EU4_CAMPAIGN_STATE" >&2
fi

WORKSPACE=$(CDPATH= cd -- "$WORKSPACE" && pwd)
STAMP=$(date -u +%Y%m%dT%H%M%SZ)
if [ -z "$OUT" ]; then
  OUT=$INFRA/.local/dsh-pilots/$STAMP
fi
case "$OUT" in
  /*) ;;
  *) OUT=$INFRA/$OUT ;;
esac
mkdir -p "$OUT"
OUT=$(CDPATH= cd -- "$OUT" && pwd)
OVERLAY=$OUT/overlay.yml

cat > "$OVERLAY" <<PATCH
# Generated by dsh/scripts/run-pilot.sh for one evidenced pilot turn.
- id: skill-filesystem
  config:
    includeDefaultRoots: false
    customSkillDirs:
      - $EU4_DSH_SKILL_ROOT

- id: llm-pi-ai
  config:
    providers:
      opencode-go:
        apiKeyEnv: OPENCODE_GO_API_KEY

- id: agent-default-model
  config:
    provider: opencode-go
    model: deepseek-v4.1-flash

- insert:
    - id: eu4-tools
      name: '$INFRA/dsh/eu4-tools-plugin/lib/index.js'
      config:
        python: '$EU4_DSH_PYTHON'
        infra: '$INFRA'
PATCH

TASK=$(cat "$TASK_FILE")
cd "$WORKSPACE"

echo "run-pilot: workspace=$WORKSPACE" >&2
echo "run-pilot: out=$OUT" >&2
echo "run-pilot: python=$EU4_DSH_PYTHON" >&2

if [ -n "$SESSION" ]; then
  set -- --json --session-id "$SESSION"
else
  set -- --json
fi
set -- "$@" --permission-mode "$MODE" --approval-policy never "$TASK"

if dsh --profile headless --patch "$OVERLAY" "$@" > "$OUT/events.jsonl" \
    2> "$OUT/session.err"; then
  RC=0
else
  RC=$?
fi

# Extract the session id and the native-tool inventory from the run events.
"$EU4_DSH_PYTHON" - "$OUT/events.jsonl" "$OUT/session.json" <<'PY'
import json
import sys

events_path, result_path = sys.argv[1:3]
session_id = None
tools = []
texts = []
final_text = ""
for line in open(events_path, encoding="utf-8", errors="replace"):
    line = line.strip()
    if not line:
        continue
    try:
        event = json.loads(line)
    except json.JSONDecodeError:
        continue
    kind = event.get("type")
    if kind == "session":
        session_id = event.get("id") or (event.get("data") or {}).get("id")
    elif kind == "tool_call":
        tools.append(event.get("tool") or (event.get("data") or {}).get("tool"))
    elif kind == "text":
        texts.append(str(event.get("text") or ""))
    elif kind == "final":
        session_id = event.get("sessionId") or session_id
        final_text = str(event.get("text") or final_text)
value = {
    "schema": "eu4-dsh-pilot-run/v1",
    "session_id": session_id,
    "tool_calls": tools,
    "tool_count": len(tools),
    "final_text": final_text,
    "texts": texts[-5:],
}
open(result_path, "w", encoding="utf-8").write(
    json.dumps(value, indent=2, sort_keys=True) + "\n")
print(json.dumps(value, sort_keys=True))
PY

SESSION=$("$EU4_DSH_PYTHON" - "$OUT/session.json" <<'PY'
import json
import sys
print(json.load(open(sys.argv[1]))["session_id"] or "")
PY
)

EXPORT=
if [ -n "$SESSION" ]; then
  EXPORT=$(find "$DSH_HOME/sessions" -maxdepth 3 -type d \
    -name "$SESSION" 2>/dev/null | head -1)
fi

if [ -n "$EXPORT" ] && [ -f "$EXPORT/session.v4.jsonl.zstd" ]; then
  if ( cd "$INFRA" && "$EU4_DSH_PYTHON" -m automation.dsh_efficiency analyze \
        "$EXPORT" --out "$OUT/efficiency.json" \
        > "$OUT/efficiency.stdout" 2> "$OUT/efficiency.err" ); then
    echo "run-pilot: export=$EXPORT" >&2
  else
    echo "run-pilot: efficiency analysis failed (see $OUT/efficiency.err)" >&2
  fi
else
  echo "run-pilot: no persisted session export found" >&2
fi

# The native-integration gate reads the actual invocation records.  Advertised
# tool definitions, bash-only runs and goal-management-only runs do not count.
set --
for name in $REQUIRE_TOOLS; do
  set -- "$@" --require-tool "$name"
done
if ( cd "$INFRA" && "$EU4_DSH_PYTHON" -m automation.dsh_pilot gate \
      --events "$OUT/events.jsonl" "$@" --out "$OUT/native-gate.json" \
      > "$OUT/native-gate.stdout" 2> "$OUT/native-gate.err" ); then
  TOOLS_STATUS=0
else
  TOOLS_STATUS=$?
fi

NATIVE=$("$EU4_DSH_PYTHON" - "$OUT/native-gate.json" <<'PY'
import json
import sys
try:
    value = json.load(open(sys.argv[1], encoding="utf-8"))
except (OSError, ValueError):
    print("")
else:
    print(",".join(value.get("native_executed") or []))
PY
)

echo "run-pilot: native_tool_calls=${NATIVE:-<none>}" >&2
if [ "${TOOLS_STATUS:-1}" -ne 0 ]; then
  cat "$OUT/native-gate.err" >&2 2>/dev/null || true
  exit 2
fi
if [ "$RC" -ne 0 ]; then
  exit "$RC"
fi
exit 0
